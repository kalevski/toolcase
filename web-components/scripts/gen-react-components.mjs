// Generates src/react-components.ts — one typed React wrapper per tc-* element.
//
// Facts come from scripts/component-manifest.mjs, shared with gen-react-types.mjs, so
// the wrappers and the JSX typings can never disagree about an element's surface.
//
// What a wrapper adds over plain JSX (which is correct on its own as of this
// release) is in src/createTcComponent.ts: JS-only props assigned as instance
// properties, camelCase event handlers, and a ref typed as the element's class.
//
// Every import here is `import type`, so importing one wrapper does not drag the
// element implementations into the bundle. That also means the wrappers do NOT
// register anything — call `register()` from the main entry as usual.
//
// Run:  npm -w @toolcase/web-components run gen:react-components
import { writeFileSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'
import { collectComponents } from './component-manifest.mjs'

const here = dirname(fileURLToPath(import.meta.url))
const srcDir = join(here, '..', 'src')

const components = collectComponents()

const typeImports = new Map()
const importType = (module, name) => {
    let names = typeImports.get(module)
    if (!names) {
        names = new Map()
        typeImports.set(module, names)
    }
    if (!names.has(name)) names.set(name, `${module.replace(/[./-]/g, '_')}$${name}`)
    return names.get(name)
}

const camel = (kebab) => kebab.replace(/-([a-z0-9])/g, (_, c) => c.toUpperCase())
const pascal = (kebab) =>
    kebab
        .split('-')
        .map((s) => s.charAt(0).toUpperCase() + s.slice(1))
        .join('')

/** Render a type descriptor, registering whatever imports it needs. */
const render = (descriptor) => {
    if (!descriptor) return null
    if (descriptor.kind === 'boolean') return 'boolean'
    if (descriptor.kind === 'raw') return descriptor.text
    if (descriptor.kind === 'named') return importType(descriptor.module, descriptor.name)
    // 'expr' — substitute each referenced type name with its local alias.
    let text = descriptor.text
    for (const ref of descriptor.refs) {
        const alias = importType(ref.module, ref.name)
        text = text.replace(new RegExp(`\\b${ref.name}\\b`, 'g'), alias)
    }
    return text
}

const bodies = []
const names = new Set()

for (const c of components) {
    const name = pascal(c.tag)
    if (names.has(name)) throw new Error(`duplicate wrapper name ${name} for ${c.tag}`)
    names.add(name)

    const element = c.file ? importType(`./${c.file}`, c.exportName) : 'HTMLElement'
    const props = []
    const propNames = []

    for (const attr of c.attrs) {
        propNames.push(camel(attr.name))
        props.push(`    ${camel(attr.name)}?: ${render(attr.type)}`)
    }
    const eventMap = []
    for (const event of c.events) {
        const prop = `on${pascal(event.name)}`
        const detail = render(event.detail)
        propNames.push(prop)
        props.push(
            `    ${prop}?: (e: ${detail ? `CustomEvent<${detail}>` : 'CustomEvent'}) => void`,
        )
        eventMap.push(`${prop}: '${event.name}'`)
    }
    for (const jsProp of c.jsProps) {
        propNames.push(jsProp.name)
        props.push(`    ${jsProp.name}?: ${render(jsProp.type)}`)
    }

    const config = []
    if (c.attrs.length) {
        config.push(`    attributes: [${c.attrs.map((a) => `'${a.name}'`).join(', ')}],`)
    }
    if (eventMap.length) config.push(`    events: { ${eventMap.join(', ')} },`)
    if (c.jsProps.length) {
        config.push(`    properties: [${c.jsProps.map((p) => `'${p.name}'`).join(', ')}],`)
    }

    // Every prop this element declares is REMOVED from the shared base first.
    // Several elements own a name React also owns — `onChange` on tc-form-input is
    // `(value, hasError) => void`, not a FormEventHandler — and an intersection of
    // two different function types is an overload set nothing satisfies.
    const owned = propNames.map((n) => `'${n}'`).join(' | ')
    const base = propNames.length ? `Omit<TcBaseProps, ${owned}>` : 'TcBaseProps'

    bodies.push(
        `export type ${name}Props = ${base}${props.length ? ` & {\n${props.join('\n')}\n}` : ''}`,
    )
    bodies.push(``)
    bodies.push(
        `export const ${name} = /*#__PURE__*/ createTcComponent<${name}Props, ${element}>('${c.tag}'${
            config.length ? `, {\n${config.join('\n')}\n})` : ')'
        }`,
    )
    bodies.push(``)
}

const lines = []
lines.push(`// AUTO-GENERATED by scripts/gen-react-components.mjs — do not edit by hand.`)
lines.push(`// One typed React wrapper per tc-* element.`)
lines.push(`//`)
lines.push(
    `//     import { TcButton, TcFormInput } from '@toolcase/web-components/react/components'`,
)
lines.push(`//`)
lines.push(
    `//     <TcFormInput label="Email" value={email} onTcChange={e => setEmail(e.detail.value)} />`,
)
lines.push(`//`)
lines.push(`// Attributes take their camelCase name here ('validate-on' → validateOn); the`)
lines.push(`// wrapper writes the kebab-case attribute. Events take a camelCase handler`)
lines.push(`// ('tc-change' → onTcChange) because the wrapper calls addEventListener itself.`)
lines.push(`// JS-only props (arrays, objects, callbacks) are ASSIGNED to the instance rather`)
lines.push(`// than stringified into an attribute.`)
lines.push(`//`)
lines.push(`// Type-only imports throughout, so importing a wrapper pulls in no element`)
lines.push(`// implementation — call register() from the main entry as usual.`)
lines.push(`//`)
lines.push(`// Regenerate after adding/removing a component, attribute or event:`)
lines.push(`//     npm -w @toolcase/web-components run gen:react`)
lines.push(``)
lines.push(`import { createTcComponent } from './createTcComponent'`)
lines.push(`import type { TcBaseProps } from './createTcComponent'`)
for (const [module, entries] of [...typeImports.entries()].sort((a, b) =>
    a[0].localeCompare(b[0]),
)) {
    const specs = [...entries.entries()]
        .sort((a, b) => a[0].localeCompare(b[0]))
        .map(([name, alias]) => `${name} as ${alias}`)
        .join(', ')
    lines.push(`import type { ${specs} } from '${module}'`)
}
lines.push(``)
lines.push(`export type { TcBaseProps } from './createTcComponent'`)
lines.push(`export { createTcComponent } from './createTcComponent'`)
lines.push(`export type { TcComponentConfig } from './createTcComponent'`)
lines.push(``)
lines.push(...bodies)

writeFileSync(join(srcDir, 'react-components.ts'), lines.join('\n'))

const jsPropCount = components.reduce((n, c) => n + c.jsProps.length, 0)
console.log(
    `Wrote src/react-components.ts — ${components.length} wrappers, ${jsPropCount} JS-only props typed`,
)
