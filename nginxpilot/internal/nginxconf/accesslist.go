package nginxconf

import (
	"fmt"
	"path/filepath"
	"strings"

	"github.com/kalevski/toolcase/nginxpilot/internal/config"
)

// AccessDirName is the directory under data_dir holding one generated
// htpasswd file per access list (<data_dir>/access/<name>.htpasswd). The
// engine regenerates these from config on every apply, so a password (re)set
// lands with the same reload that re-renders the referencing vhosts.
const AccessDirName = "access"

// HtpasswdPath is the generated htpasswd file for one access list. The name is
// validation-guaranteed to match [A-Za-z0-9_]+, so it is always path-safe.
func HtpasswdPath(dataDir, name string) string {
	return filepath.Join(dataDir, AccessDirName, name+".htpasswd")
}

// HtpasswdContent renders an access list's htpasswd file body: one
// "user:hash" line per user with a hash. Users whose password is still
// pending (no hash) are skipped — they can't authenticate yet, but they also
// must not produce a malformed line.
func HtpasswdContent(l *config.AccessList) string {
	var b strings.Builder
	b.WriteString("# htpasswd for access list \"" + l.Name + "\" — generated by nginxpilot; do not edit.\n")
	for _, u := range l.Users {
		if u.PasswordHash == "" {
			continue
		}
		b.WriteString(u.Username + ":" + u.PasswordHash + "\n")
	}
	return b.String()
}

// findAccessList resolves a name against the merged config (nil when absent —
// validation guarantees referenced names exist, so nil only happens in
// hand-rolled tests).
func findAccessList(cfg *config.Config, name string) *config.AccessList {
	for i := range cfg.AccessLists {
		if cfg.AccessLists[i].Name == name {
			return &cfg.AccessLists[i]
		}
	}
	return nil
}

// writeAccessControl emits the server-level directives for a referenced
// access list: `satisfy`, the ordered allow/deny rules closed with a final
// `deny all;`, and basic auth against the generated htpasswd file. Every
// value is validation-vetted (IP/CIDR/"all", safe identifier name), so no
// unvetted string reaches the rendered file.
func writeAccessControl(b *strings.Builder, cfg *config.Config, name string) {
	if name == "" {
		return
	}
	l := findAccessList(cfg, name)
	if l == nil {
		return
	}
	fmt.Fprintf(b, "\n    # access list: %s (managed by nginxpilot)\n", l.Name)
	if l.SatisfyOrAll() == config.SatisfyAny {
		b.WriteString("    satisfy any;\n")
	}
	for _, r := range l.Rules {
		if r.Allow != "" {
			fmt.Fprintf(b, "    allow %s;\n", r.Allow)
		} else {
			fmt.Fprintf(b, "    deny %s;\n", r.Deny)
		}
	}
	if len(l.Rules) > 0 {
		b.WriteString("    deny all;\n")
	}
	if l.HasUsers() {
		b.WriteString("    auth_basic \"Restricted\";\n")
		fmt.Fprintf(b, "    auth_basic_user_file %s;\n", HtpasswdPath(cfg.DataDir, l.Name))
	}
}

// consumesAuthHeader reports whether a proxy's access list wants the client's
// Authorization header consumed at the edge (basic auth in use and pass_auth
// off) — the locations then blank the header before proxy_pass.
func consumesAuthHeader(cfg *config.Config, name string) bool {
	if name == "" {
		return false
	}
	l := findAccessList(cfg, name)
	return l != nil && l.HasUsers() && !l.PassAuth
}
